import fs from 'fs';
import path from 'path';
import type {LoadContext, Plugin} from '@docusaurus/types';
import {PROJECTS, type Project} from '../src/projects';

// Writes llms.txt (https://llmstxt.org) after the build: a site-wide index of the projects at
// /llms.txt, plus one /<id>/llms-full.txt per project holding the full text of its served docs
// (lastVersion if it has one, else current), in sidebar order. Changelogs are left out: old ones
// show old config syntax, which a model would happily copy as current.

type SidebarItem =
  | string
  | {type: 'doc'; id: string}
  | {type: 'category'; items: SidebarItem[]; link?: {type: string; id?: string}}
  | {type: 'autogenerated'; dirName: string}
  | {type: string; [key: string]: unknown};

/** The served docs folder and its sidebar (null when the project has no JSON sidebar to follow). */
function servedDocs(siteDir: string, p: Project): {dir: string; sidebar: SidebarItem[] | null} {
  if (p.lastVersion) {
    const sidebarFile = path.join(siteDir, `${p.id}_versioned_sidebars`, `version-${p.lastVersion}-sidebars.json`);
    return {
      dir: path.join(siteDir, `${p.id}_versioned_docs`, `version-${p.lastVersion}`),
      sidebar: fs.existsSync(sidebarFile) ? JSON.parse(fs.readFileSync(sidebarFile, 'utf8')).docs : null,
    };
  }
  return {dir: path.join(siteDir, 'projects', p.id, 'docs'), sidebar: null};
}

/** Every doc file under dir, relative, without extension, sorted with index pages first. */
function listDocs(dir: string, sub = ''): string[] {
  const here = path.join(dir, sub);
  if (!fs.existsSync(here)) return [];
  const entries = fs.readdirSync(here, {withFileTypes: true}).sort((a, b) => a.name.localeCompare(b.name));
  const files = entries
    .filter((e) => e.isFile() && /\.mdx?$/.test(e.name))
    .map((e) => path.posix.join(sub, e.name.replace(/\.mdx?$/, '')))
    .sort((a, b) => Number(path.basename(b) === 'index') - Number(path.basename(a) === 'index'));
  const dirs = entries.filter((e) => e.isDirectory()).flatMap((e) => listDocs(dir, path.posix.join(sub, e.name)));
  return [...files, ...dirs];
}

/** Doc ids in the order the sidebar shows them, then anything the sidebar doesn't mention. */
function orderedDocs(dir: string, sidebar: SidebarItem[] | null): string[] {
  const all = listDocs(dir);
  if (!sidebar) return all;
  const ordered: string[] = [];
  const walk = (items: SidebarItem[]) => {
    for (const item of items) {
      if (typeof item === 'string') ordered.push(item);
      else if (item.type === 'doc') ordered.push(item.id as string);
      else if (item.type === 'autogenerated') {
        const dirName = item.dirName as string;
        ordered.push(...all.filter((id) => id.startsWith(`${dirName}/`)));
      } else if (item.type === 'category') {
        const link = item.link as {type: string; id?: string} | undefined;
        if (link?.type === 'doc' && link.id) ordered.push(link.id);
        walk(item.items as SidebarItem[]);
      }
    }
  };
  walk(sidebar);
  const seen = new Set<string>();
  return [...ordered, ...all].filter((id) => all.includes(id) && !seen.has(id) && seen.add(id));
}

/** Markdown with frontmatter, MDX imports and JSX-only lines (ads, <center>) removed. */
function cleanMarkdown(source: string): string {
  return source
    .replace(/^---\n[\s\S]*?\n---\n/, '')
    .split('\n')
    .filter((line) => !/^import\s.+from\s/.test(line))
    .filter((line) => !/^\s*<\/?[A-Za-z][^>]*\/?>\s*$/.test(line))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function docUrl(siteUrl: string, p: Project, id: string): string {
  const route = id === 'index' ? '' : id.replace(/(^|\/)index$/, '');
  return `${siteUrl}/${p.id}/${route.split('/').map(encodeURIComponent).join('/')}`;
}

export default function llmsPlugin(context: LoadContext): Plugin {
  return {
    name: 'llms-txt',
    async postBuild({outDir}) {
      const siteUrl = context.siteConfig.url.replace(/\/$/, '');
      const sections: string[] = [];

      for (const p of PROJECTS) {
        const {dir, sidebar} = servedDocs(context.siteDir, p);
        const ids = orderedDocs(dir, sidebar).filter((id) => !id.split('/').includes('Changelogs'));
        if (ids.length === 0) continue;

        const pages = ids.map((id) => {
          const file = ['.md', '.mdx'].map((ext) => path.join(dir, id + ext)).find(fs.existsSync)!;
          return `<!-- Source: ${docUrl(siteUrl, p, id)} -->\n\n${cleanMarkdown(fs.readFileSync(file, 'utf8'))}`;
        });
        const version = p.lastVersion ? ` (docs for version ${p.lastVersion})` : '';
        const full = `# ${p.label}${version}\n\n> ${p.blurb}\n\n${pages.join('\n\n---\n\n')}\n`;
        fs.mkdirSync(path.join(outDir, p.id), {recursive: true});
        fs.writeFileSync(path.join(outDir, p.id, 'llms-full.txt'), full);

        const links = [
          `- [Documentation](${siteUrl}/${p.id}/)`,
          `- [Full documentation as text](${siteUrl}/${p.id}/llms-full.txt)`,
          p.modrinth && `- [Modrinth](${p.modrinth})`,
          p.curseforge && `- [CurseForge](${p.curseforge})`,
        ].filter(Boolean);
        sections.push(`## ${p.label}\n\n${p.blurb} (Minecraft ${p.kind})\n\n${links.join('\n')}`);
      }

      const index = [
        `# ${context.siteConfig.title}`,
        `> Documentation for Minecraft mods and plugins by BeepSterr.`,
        ...sections,
      ].join('\n\n');
      fs.writeFileSync(path.join(outDir, 'llms.txt'), `${index}\n`);
    },
  };
}
